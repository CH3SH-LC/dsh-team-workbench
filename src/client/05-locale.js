/** Interpolate `{name}` placeholders; missing keys echo the key (host dictionary discipline). */
function tbFormat(t, key, values) {
  let text;
  try {
    text = t(key);
  } catch (error) {
    console.error('[team-workbench] locale lookup failed:', error);
    return key;
  }
  if (typeof text !== 'string') text = key;
  if (values === undefined) return text;
  return text.replace(/\{([a-zA-Z0-9_]+)\}/g, (match, name) => (Object.prototype.hasOwnProperty.call(values, name) ? String(values[name]) : match));
}
